// ====================================================================
// User_Setup.h — конфигурация дисплея ST7789V для TFT_eSPI
// Проект: GameDesk (ESP32 + TFT 2.8" 320x240, SPI)
// Версия: с включённым сглаживанием (SMOOTH_FONT) и шрифтом 6
// ====================================================================

// --------------------------------------------------------------------
// 1. Выбор драйвера дисплея (ST7789V)
// --------------------------------------------------------------------
#define ST7789_DRIVER

// --------------------------------------------------------------------
// 2. Размеры дисплея (исходная ориентация — портрет 240x320)
// --------------------------------------------------------------------
#define TFT_WIDTH  240
#define TFT_HEIGHT 320

// --------------------------------------------------------------------
// 3. SPI-пины ESP32 (VSPI)
// --------------------------------------------------------------------
#define TFT_MOSI  23
#define TFT_MISO  19            // можно оставить, даже если не используется
#define TFT_SCLK  18

// --------------------------------------------------------------------
// 4. Управляющие пины
// --------------------------------------------------------------------
#define TFT_CS    15
#define TFT_DC    2
#define TFT_RST   4

// --------------------------------------------------------------------
// 5. Подсветка (LED) — GPIO21
// --------------------------------------------------------------------
#define TFT_BL    21
#define TFT_BACKLIGHT_ON HIGH

// --------------------------------------------------------------------
// 6. Частота SPI (40 МГц)
// --------------------------------------------------------------------
#define SPI_FREQUENCY  40000000
#define SPI_READ_FREQUENCY  20000000
#define SPI_TOUCH_FREQUENCY  2500000

// --------------------------------------------------------------------
// 7. Включение транзакций и DMA (ускоряет отрисовку)
// --------------------------------------------------------------------
#define SUPPORT_TRANSACTIONS
#define ESP32_DMA

// --------------------------------------------------------------------
// 8. ЗАГРУЗКА ШРИФТОВ — сглаживание включено
// --------------------------------------------------------------------
#define LOAD_GLCD          // базовый шрифт
#define LOAD_FONT2         // шрифт 2 (для текста)
#define LOAD_FONT4         // шрифт 4 (для крупного текста)
#define LOAD_FONT6         // шрифт 6 (для логотипа GAME/DESK)

// --------------------------------------------------------------------
// 9. СГЛАЖИВАНИЕ ШРИФТОВ — ВКЛЮЧЕНО
//     Это позволит использовать загружаемые сглаженные шрифты (.vlw)
//     и улучшит внешний вид крупных надписей.
// --------------------------------------------------------------------
#define SMOOTH_FONT 1       // ВКЛЮЧАЕМ СГЛАЖИВАНИЕ (было 0)

// --------------------------------------------------------------------
// 10. Загрузка шрифтов GFXFF (для совместимости)
//     Некоторые сглаженные шрифты требуют этот флаг.
// --------------------------------------------------------------------
#define LOAD_GFXFF         // загружаем поддержку шрифтов GFXFF

// --------------------------------------------------------------------
// 11. Остальные настройки
// --------------------------------------------------------------------
// #define TFT_ROTATION 1   // можно задать жёстко, но лучше из скетча

#define USER_SETUP_INFO "GameDesk ST7789V 320x240 SPI VSPI SMOOTH"