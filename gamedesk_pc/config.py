import json
import os

"""
Конфигурационный модуль для GameDesk.
"""

# ----------------------------------------------------------------------
# Список отслеживаемых игр (читается из внешнего файла)
# ----------------------------------------------------------------------
GAMES_LIST_FILE = "games_list.json"

def load_games():
    # Если файла нет, создаем его со стандартным списком
    if not os.path.exists(GAMES_LIST_FILE):
        default_games = {
            "sublime_text.exe": "Sublime Text",
            "forzahorizon6.exe": "Forza Horizon 6"
        }
        with open(GAMES_LIST_FILE, 'w', encoding='utf-8') as f:
            json.dump(default_games, f, ensure_ascii=False, indent=4)
        return default_games
    
    # Если файл есть, читаем список из него
    with open(GAMES_LIST_FILE, 'r', encoding='utf-8') as f:
        return json.load(f)

GAMES = load_games()

